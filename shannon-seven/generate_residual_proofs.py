"""Regenerate the Lean residual modules with the pinned toolchain's CaDiCaL."""
import argparse
import itertools
from pathlib import Path
import subprocess
from tempfile import TemporaryDirectory

from check_projection import HERE, close


def used_steps(proof, original_count):
    # Keep the empty clause and its ancestors. Mathlib checks every retained hint.
    derived = {}
    final = None
    for line in proof.splitlines():
        fields = line.split()
        if fields[1] == "d":
            continue
        values = list(map(int, fields))
        split = values.index(0, 1)
        derived[values[0]] = line, values[split + 1:-1]
        if split == 1:
            final = values[0]
            break
    if final is None:
        raise ValueError("The LRAT trace contains no derivation of the empty clause")
    needed = {final}
    for index in reversed(derived):
        if index in needed:
            needed.update(h for h in derived[index][1] if h > original_count)
    return "\n".join(line for i, (line, _) in derived.items() if i in needed)


def module(axis, projection, indices, code, solver, temporary):
    points = [code[i][:axis] + code[i][axis + 1:] for i in indices]
    points.append(tuple(map(int, projection)))
    edges = [(i, j) for i, j in itertools.combinations(range(len(points)), 2)
             if close(points[i], points[j])]
    # DIMACS variables start at 1. 'encoding' in Refutation.lean starts at 0.
    def var(i, symbol):
        return 7 * i + symbol + 1

    clauses = [[var(i, b) for b in range(7)] for i in range(len(points))]
    for i, j in edges:
        clauses.extend([-var(i, b), -var(j, d)] for b in range(7) for d in range(7)
                       if (b - d) % 7 in (0, 1, 6))
    clauses.append([var(len(points) - 1, 0)])
    dimacs = f"p cnf {7 * len(points)} {len(clauses)}\n" + "\n".join(
        " ".join(map(str, c)) + " 0" for c in clauses)
    cnf = temporary / "input.cnf"
    proof = temporary / "proof.lrat"
    cnf.write_text(dimacs + "\n")
    result = subprocess.run([solver, "-q", "--plain", "--lrat", "--no-binary", cnf, proof],
                            stdout=subprocess.PIPE, text=True)
    if result.returncode != 20:
        raise RuntimeError(f"Expected an UNSAT certificate for {axis}, {projection}")
    trace = used_steps(proof.read_text(), len(clauses))
    name = f"C{axis}{projection}"
    body = f'''import Shannon.Refutation

/-! Generated by shannon-seven/generate_residual_proofs.py.
Coordinate {axis + 1}, additional four-symbol projection {projection}. -/
namespace Shannon.Seven.{name}

set_option maxRecDepth 64000
set_option maxHeartbeats 0

def ids : List Nat := {indices + [367]}
def edges : List Edge := {edges}

theorem unsat : (encoding ids.length edges).proof [] := checked_lrat
  "{dimacs}"
  "{trace}"

end Shannon.Seven.{name}
'''
    return name, body


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--solver", default="cadical")
    args = parser.parse_args()
    code = [tuple(map(int, w)) for w in (HERE / "polak_schrijver.txt").read_text().split()]
    output = HERE.parent / "lean-qutrit" / "Shannon" / "Cores"
    output.mkdir(exist_ok=True)
    with TemporaryDirectory() as temp:
        for line in (HERE / "projection_cores.txt").read_text().splitlines():
            axis, p, *ids = line.split()
            name, text = module(int(axis), p, list(map(int, ids)), code, args.solver, Path(temp))
            (output / f"{name}.lean").write_text(text)


if __name__ == "__main__":
    main()
