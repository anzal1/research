"""Search the order-29 angular family over GF(2^14) and reconstruct Lean certificates."""
import argparse
from pathlib import Path

MODULUS = 0x7303  # trace of a primitive 29th root; proved in Order29.lean
Q = 1 << 14


def binary_product(a, b):
    result = 0
    while b:
        if b & 1:
            result ^= a
        b >>= 1
        a <<= 1
        if a & Q:
            a ^= MODULUS
    return result


def field_tables():
    for generator in range(2, Q):
        log, exp = [-1]*Q, []
        a = 1
        while log[a] == -1 and a:
            log[a] = len(exp)
            exp.append(a)
            a = binary_product(a, generator)
        if len(exp) == Q-1 and a == 1:
            return log, exp + exp
    raise ArithmeticError('No full multiplicative cycle')


LOG, EXP = field_tables()


def mul(a, b):
    return EXP[LOG[a]+LOG[b]] if a and b else 0


def power(a, n):
    if n == 0:
        return 1
    return EXP[(LOG[a]*n) % (Q-1)] if a else 0


def trim(p):
    while p and not p[-1]:
        p.pop()
    return p


def add(a, b):
    p = list(a) + [0]*max(0,len(b)-len(a))
    for i, x in enumerate(b):
        p[i] ^= x
    return trim(p)


def product(a, b):
    out = [0]*(len(a)+len(b))
    for i,x in enumerate(a):
        if x:
            for j,y in enumerate(b):
                out[i+j] ^= mul(x,y)
    return trim(out)


def divide(a, b):
    if not b:
        raise ZeroDivisionError
    r, quot = list(a), [0]*max(0,len(a)-len(b)+1)
    inv = power(b[-1], Q-2)
    while len(r) >= len(b):
        k = len(r)-len(b)
        quot[k] = c = mul(r[-1], inv)
        for j,y in enumerate(b):
            r[j+k] ^= mul(c,y)
        trim(r)
    return trim(quot), r


def bezout(a, b):
    x, y, u, v = [1], [], [], [1]
    while b:
        q, r = divide(a,b)
        a,b = b,r
        x,u = u,add(x,product(q,u))
        y,v = v,add(y,product(q,v))
    return a,x,y


def obstruction(scale):
    # D5((1+Z^5)/(scale*Z)) = D5(theta), where D5(T) = T^5+T^3+T.
    m, z = [1,0,0,0,0,1], [0,scale]
    m2, z2 = product(m,m), product(z,z)
    m4, z4 = product(m2,m2), product(z2,z2)
    return add(add(product(m4,m),product(product(m2,m),z2)),
               add(product(m,z4),product([0x2a],product(z4,z))))


def frobenius(f, count):
    x, rows = [0,1], []
    for _ in range(count):
        square = [0]*(2*len(x)-1)
        square[::2] = [mul(a,a) for a in x]
        quotient, x = divide(square,f)
        rows.append((quotient,x))
    return rows


def search(start, stop):
    for scale in range(start, stop + 1):
        f = obstruction(scale)
        r14 = frobenius(f,14)[-1][1]
        if len(bezout(f,add(r14,[0,1]))[0]) == 1:
            return scale, f
    return None


def lean_list(row):
    return '[' + ','.join(hex(i) for i in row) + ']'


def certificate_file(scale, f, rows):
    gcd,a,b = bezout(f,add(rows[13][1],[0,1]))
    if len(gcd) != 1 or rows[-1][1] != [0,1]:
        raise ValueError('Required Frobenius or Bezout certificate is missing')
    inv=power(gcd[0],Q-2)
    lines=['import Qmds.RayCertificate', '', '/-! Generated by search_rays.py --emit. Each row witnesses a squaring modulo f. -/',
           'namespace Qmds.Order29.Data','open BinaryCertificate RayCertificate',
           'set_option Elab.async false','set_option maxHeartbeats 0','set_option maxRecDepth 100000',
           'def modulus := bits 0x7303', f'def scalar := bits {hex(scale)}',
           f'def f := decode {lean_list(f)}','def zvar : B := [[],one]',
           f'def bezA := decode {lean_list([mul(c,inv) for c in a])}',
           f'def bezB := decode {lean_list([mul(c,inv) for c in b])}']
    for i in range(10):
        chunk=rows[7*i:7*i+7]
        lines += [f'def rows{i} : List (List Nat × List Nat) := [',
                  ',\n'.join('  ('+lean_list(q)+', '+lean_list(r)+')' for q,r in chunk)+']',
                  f'def r{i+1} := decode {lean_list(chunk[-1][1])}',
                  f'theorem check{i} : RayCertificate.chain modulus f '+('zvar' if i==0 else f'r{i}')+
                  f' rows{i} = true := by decide +kernel']
    lines += ['theorem unit : norm (add (product modulus bezA f) (product modulus bezB (add r2 zvar))) = [one] := by decide +kernel',
              'end Qmds.Order29.Data','']
    return '\n'.join(lines)


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--emit',type=Path,help='write the Lean certificate module')
    parser.add_argument('--check-file',type=Path,help='compare the reconstructed module byte for byte')
    parser.add_argument('--start', type=int, default=1, help='first scale to try (inclusive)')
    parser.add_argument('--stop', type=int, default=Q-1, help='last scale to try (inclusive)')
    args=parser.parse_args()
    if not 1 <= args.start <= args.stop < Q:
        parser.error('expected 1 <= start <= stop <= 16383')
    winner = search(args.start, args.stop)
    if winner is None:
        if args.emit or args.check_file:
            raise ValueError('No certificate-producing scale in the selected interval')
        print(f'order 29: no zero-free radial polynomial at scales {args.start} through {args.stop}')
        raise SystemExit(0)
    scale, f = winner
    rows=frobenius(f,70)
    if args.emit or args.check_file:
        certificate=certificate_file(scale,f,rows)
    if args.emit:
        args.emit.write_text(certificate)
    if args.check_file and args.check_file.read_text()!=certificate:
        raise ValueError('Checked-in certificate differs from fresh search')
    period = 'passes' if rows[-1][1] == [0,1] else 'fails'
    print(f'order 29: {scale-args.start+1} scales searched from {args.start}; first zero-free radial polynomial at {scale:#x}; degree {len(f)-1}; 70-step test {period}')
